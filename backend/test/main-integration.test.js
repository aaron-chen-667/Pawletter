 assert.deepEqual((await adopter.facts(pet.id)).notes.map(n=>n.quote),['疫苗日期待确认。']);
 await station.updateAgent(pet.id,{tone:'calm',style:'简短自然'});
 assert.equal((await station.agent(pet.id)).voice.tone,'calm');
