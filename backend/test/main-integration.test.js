 assert.ok((await adopter.facts(pet.id)).notes.every(n=>n.quote!==text));
 await station.withdrawObservation(replacement.id);
 assert.deepEqual((await adopter.facts(pet.id)).notes.map(n=>n.quote),['疫苗日期待确认。']);
